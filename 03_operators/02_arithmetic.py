
# arithmetic operator 


# addition +


num1=10;

num2=20;

result = num1 + num2;

print("addition",result)


# subtraction -

result = num2 - num1;

print("subtraction",result)


# multiplication  *

result = num1 * num2;

print("multiplication",result)

# division /

result = num2/num1

print("division",result)

# floor division //

result = num2//num1;

print("floor division",result)

# modulo %

result = num2%num1;

print("modulo",result)


# exponential  **

result = num2**3;

print("exponential",result)