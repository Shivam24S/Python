

# in and not in 

fruits=["apple","banana",'Cherry',"litchi"]


# false case
print("is mango available in fruits list ?", "mango" in fruits )

# true case
print("is mango available in fruits list ?", "litchi" in fruits )




# not in 


# true case 
print("is pineapple available in fruits list ","pineapple" not in fruits)

# false case
print("is pineapple available in fruits list ","apple" not in fruits)